import json
import os
import secrets
import shutil
import subprocess
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from mellyn.credentials import DIGEST_ENV, PEPPER_ENV, CredentialConfig, Role, key_digest
from mellyn.egress_proxy import generate_squid_config, validate_egress_domain
from mellyn.gateway_config import load_gateway_config
from mellyn.legacy_env import check_no_legacy_env
from mellyn.models import RiskTier
from mellyn.policy import SMB_SERVER_PRESETS, ServerPresetProfile
from mellyn.policy_loader import PolicyLoadError, load_policy_file, parse_policy_dict
from mellyn.unified_config import (
    load_gateway_egress_domains_any,
    load_policy_any,
    load_unified_config,
    render_unified_config,
)


class InitError(RuntimeError):
    """Raised fail-closed when workspace bootstrap or pre-flight validation fails."""


# Generated configs go in their own folder, which compose mounts read-only at /etc/mellyn. It is kept apart from
# `.env` on purpose: anything in the mounted folder is readable inside the containers, including by MCP servers.
CONFIG_SUBDIR = "config"
POLICY_FILENAME = "mellyn-policy.toml"
GATEWAY_FILENAME = "mellyn-gateway.toml"
UNIFIED_CONFIG_FILENAME = "mellyn.toml"

# Compose variables (see deploy/docker-compose.yml) and the defaults compose falls back to.
CONFIG_DIR_ENV = "MELLYN_CONFIG_DIR"
POLICY_FILE_ENV = "MELLYN_POLICY_FILE"
GATEWAY_FILE_ENV = "MELLYN_GATEWAY_CONFIG_FILE"
ENV_FILE_ENV = "MELLYN_ENV_FILE"
DEFAULT_POLICY_FILE = "mellyn-policy.example.toml"
DEFAULT_GATEWAY_FILE = "mellyn-gateway.example.toml"


@dataclass(frozen=True)
class CredentialsBundle:
    """Server-side pepper + HMAC-SHA256 digests + one-time raw keys generated by `mellyn init`."""

    pepper: str
    agent_key: str
    approver_key: str
    agent_digest: str
    approver_digest: str


@dataclass(frozen=True)
class InitResult:
    """Artifacts generated by `init_workspace()`."""

    env_path: Path
    policy_path: Path | None
    gateway_path: Path | None
    squid_path: Path | None
    credentials: CredentialsBundle
    presets: tuple[str, ...]
    mellyn_config_path: Path | None = None


def generate_credentials_bundle() -> CredentialsBundle:
    """Generate distinct pepper and role keys alongside their HMAC-SHA256 digests."""
    pepper = secrets.token_urlsafe(32)
    agent_key = secrets.token_urlsafe(32)
    approver_key = secrets.token_urlsafe(32)
    while approver_key == agent_key:
        approver_key = secrets.token_urlsafe(32)

    agent_digest = key_digest(agent_key, pepper)
    approver_digest = key_digest(approver_key, pepper)

    # Validate through CredentialConfig itself so role separation invariants match runtime startup.
    CredentialConfig.from_env(
        {
            PEPPER_ENV: pepper,
            DIGEST_ENV["agent"]: agent_digest,
            DIGEST_ENV["approver"]: approver_digest,
        },
        roles=frozenset({Role.AGENT, Role.APPROVER}),
    )
    return CredentialsBundle(
        pepper=pepper,
        agent_key=agent_key,
        approver_key=approver_key,
        agent_digest=agent_digest,
        approver_digest=approver_digest,
    )


def _resolve_presets(presets: Sequence[str]) -> tuple[ServerPresetProfile, ...]:
    if not presets:
        raise InitError("Select at least one preset (see `mellyn presets`).")
    profiles: list[ServerPresetProfile] = []
    seen: set[str] = set()
    for raw_name in presets:
        name = raw_name.strip().lower()
        if name not in SMB_SERVER_PRESETS:
            known = ", ".join(sorted(SMB_SERVER_PRESETS))
            raise InitError(f"Unknown preset '{raw_name}'. Known presets: {known}.")
        if name in seen:
            continue
        seen.add(name)
        profiles.append(SMB_SERVER_PRESETS[name])
    return tuple(profiles)


def render_env_file(
    bundle: CredentialsBundle,
    *,
    workspace_root: Path | None = None,
    team: bool = False,
    config_dir: Path | None = None,
    policy_filename: str = POLICY_FILENAME,
    gateway_filename: str = GATEWAY_FILENAME,
) -> str:
    """
    Render `.env` holding the pepper and key digests ONLY (raw role keys are never written).

    With `config_dir`, it also tells compose where the generated policy and gateway config are, so `mellyn up`
    runs the containers on them rather than on the checked-in examples.
    """
    lines = [
        "# Generated by `mellyn init`. Protect this file (mode 0600) and never commit it.",
        f"MELLYN_ENV={'production' if team else 'development'}",
        f"{PEPPER_ENV}={bundle.pepper}",
        f"{DIGEST_ENV['agent']}={bundle.agent_digest}",
        f"{DIGEST_ENV['approver']}={bundle.approver_digest}",
        "MELLYN_LOG_LEVEL=INFO",
        "MELLYN_STRICT_MODE=true",
    ]
    if workspace_root is not None:
        lines.append(f"MELLYN_WORKSPACE={workspace_root.resolve()}")
    if config_dir is not None:
        lines.extend(
            [
                f"{CONFIG_DIR_ENV}={config_dir.resolve()}",
                f"{POLICY_FILE_ENV}={policy_filename}",
                f"{GATEWAY_FILE_ENV}={gateway_filename}",
            ]
        )
    lines.append("")
    return "\n".join(lines)


def render_starter_policy(
    presets: Sequence[str],
    *,
    extra_domains: Sequence[str] = (),
) -> str:
    """Render and validate a starter `mellyn-policy.toml` from curated SMB presets."""
    profiles = _resolve_presets(presets)
    domains: list[str] = []
    seen_domains: set[str] = set()
    for prof in profiles:
        for dom in prof.egress_domains:
            norm = validate_egress_domain(dom)
            if norm not in seen_domains:
                seen_domains.add(norm)
                domains.append(norm)
    for raw_dom in extra_domains:
        try:
            norm = validate_egress_domain(raw_dom)
        except ValueError as exc:
            raise InitError(f"Invalid egress domain '{raw_dom}': {exc}") from exc
        if norm not in seen_domains:
            seen_domains.add(norm)
            domains.append(norm)

    allowed_servers = [prof.default_server_name for prof in profiles]
    trusted_servers = [prof.default_server_name for prof in profiles if prof.trusted]

    def _toml_list(items: Sequence[str]) -> str:
        return json.dumps(list(items))

    lines = [
        "# Mellyn Security — Turn-Key MCP Authorization Policy",
        "# Generated by `mellyn init` and verified fail-closed by `mellyn.policy_loader`.",
        "",
        "schema_version = 1",
        f"allowed_mcp_servers = {_toml_list(allowed_servers)}",
        f"trusted_mcp_servers = {_toml_list(trusted_servers)}",
        f"allowed_egress_domains = {_toml_list(domains)}",
        "protected_paths = []",
        "",
        "injection_escalate_threshold = 0.70",
        "injection_deny_threshold = 0.90",
        "deny_on_dlp_secret = true",
        "",
        "[server_presets]",
    ]
    for prof in profiles:
        lines.append(f"{json.dumps(prof.default_server_name)} = {json.dumps(prof.preset_name)}")

    lines.append("")
    lines.append("[tool_risk_tiers]")
    for prof in profiles:
        for tool_name, tier in prof.default_tool_risk_tiers.items():
            qualified = f"{prof.default_server_name}/{tool_name}"
            tier_str = tier.value if isinstance(tier, RiskTier) else str(tier)
            lines.append(f"{json.dumps(qualified)} = {json.dumps(tier_str)}")

    lines.extend(
        [
            "",
            "[[scoped_rules]]",
            'rule_id = "deny-destructive-programs"',
            'tool_name = "shell_exec"',
            'effect = "deny"',
            'programs = ["rm", "curl", "wget", "nc", "ncat"]',
            'description = "Defense-in-depth denial of destructive deletion and raw network binaries."',
            "",
        ]
    )
    rendered = "\n".join(lines)
    # Fail-closed verification that the generated policy loads cleanly.
    parse_policy_dict(tomllib.loads(rendered))
    return rendered


def render_starter_gateway(
    presets: Sequence[str],
    *,
    policy_filename: str = "mellyn-policy.toml",
) -> str:
    """Render a starter `mellyn-gateway.toml` pairing with `render_starter_policy`."""
    profiles = _resolve_presets(presets)
    if not policy_filename.strip():
        raise InitError("policy_filename must not be empty.")
    lines = [
        "# Mellyn Security — MCP Gateway Configuration",
        "# Generated by `mellyn init`. Replace placeholder commands with your MCP servers.",
        "",
        "schema_version = 1",
        f"policy = {json.dumps(policy_filename.strip())}",
        "",
    ]
    for prof in profiles:
        lines.extend(
            [
                "[[servers]]",
                f"name = {json.dumps(prof.default_server_name)}",
                f"command = {json.dumps(list(prof.example_command))}",
                "",
            ]
        )
    return "\n".join(lines)


def _reject_symlink(path: Path) -> None:
    try:
        if path.is_symlink() or path.parent.is_symlink():
            raise InitError(f"Refusing symlink target '{path}'.")
    except OSError as exc:
        raise InitError(f"Unable to inspect path '{path}': {exc}") from exc


def _write_private_text(path: Path, content: str) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
    finally:
        if os.name == "posix" and path.exists() and not path.is_symlink():
            os.chmod(path, 0o600)


def init_workspace(
    target_dir: Path,
    *,
    presets: Sequence[str] = ("mcp-filesystem",),
    team: bool = False,
    workspace_root: Path | None = None,
    extra_domains: Sequence[str] = (),
    force: bool = False,
    squid_output: Path | None = None,
    unified: bool = False,
    canary_tokens: Sequence[str] = (),
) -> InitResult:
    """
    Create `.env` (digests only) and either unified `config/mellyn.toml` (`unified=True`) or, in `config/`,
    `mellyn-policy.toml` and `mellyn-gateway.toml`, plus an optional `squid.conf`.
    """
    profiles = _resolve_presets(presets)
    config_dir = target_dir / CONFIG_SUBDIR
    for directory in (target_dir, config_dir):
        if directory.is_symlink():
            raise InitError(f"Directory '{directory}' must not be a symlink.")
    config_dir.mkdir(parents=True, exist_ok=True)

    env_path = target_dir / ".env"
    mellyn_cfg_path = config_dir / UNIFIED_CONFIG_FILENAME
    policy_path = config_dir / POLICY_FILENAME
    gateway_path = config_dir / GATEWAY_FILENAME
    effective_squid_path = squid_output if squid_output is not None else (target_dir / "squid.conf" if team else None)

    targets = [env_path, mellyn_cfg_path] if unified else [env_path, policy_path, gateway_path]
    if effective_squid_path is not None:
        targets.append(effective_squid_path)

    for candidate in targets:
        _reject_symlink(candidate)
        if candidate.is_dir():
            raise InitError(f"Target path '{candidate}' is a directory.")
        if not force and candidate.exists():
            raise InitError(f"Refusing to overwrite existing file '{candidate}' without --force.")

    bundle = generate_credentials_bundle()
    env_text = render_env_file(
        bundle,
        workspace_root=workspace_root,
        team=team,
        config_dir=config_dir,
        policy_filename=UNIFIED_CONFIG_FILENAME if unified else POLICY_FILENAME,
        gateway_filename=UNIFIED_CONFIG_FILENAME if unified else GATEWAY_FILENAME,
    )
    _write_private_text(env_path, env_text)

    if unified:
        unified_text = render_unified_config(presets, extra_domains=extra_domains, canary_tokens=canary_tokens)
        mellyn_cfg_path.write_text(unified_text, encoding="utf-8", newline="\n")
        # Round-trip load generated config so fail-closed errors surface immediately.
        loaded_unified = load_unified_config(mellyn_cfg_path)
        loaded_policy = loaded_unified.policy
        gateway_domains: frozenset[str] = loaded_unified.gateway_egress_domains
        result_policy: Path | None = None
        result_gateway: Path | None = None
        result_unified: Path | None = mellyn_cfg_path
    else:
        policy_text = render_starter_policy(presets, extra_domains=extra_domains)
        gateway_text = render_starter_gateway(presets, policy_filename=policy_path.name)
        policy_path.write_text(policy_text, encoding="utf-8", newline="\n")
        gateway_path.write_text(gateway_text, encoding="utf-8", newline="\n")
        # Round-trip load generated files so fail-closed errors surface immediately.
        loaded_policy = load_policy_file(policy_path)
        gateway_domains = frozenset()
        load_gateway_config(gateway_path)
        result_policy = policy_path
        result_gateway = gateway_path
        result_unified = None

    if effective_squid_path is not None:
        effective_squid_path.parent.mkdir(parents=True, exist_ok=True)
        effective_squid_path.write_text(
            generate_squid_config(loaded_policy, gateway_domains=gateway_domains), encoding="utf-8", newline="\n"
        )

    return InitResult(
        env_path=env_path,
        policy_path=result_policy,
        gateway_path=result_gateway,
        squid_path=effective_squid_path,
        credentials=bundle,
        presets=tuple(prof.preset_name for prof in profiles),
        mellyn_config_path=result_unified,
    )


def parse_dotenv(path: Path) -> dict[str, str]:
    """Parse key=value pairs from `.env`, refusing missing files and symlinks (fail closed)."""
    if path.is_symlink() or path.parent.is_symlink():
        raise InitError(f"Refusing symlink env file '{path}'.")
    if not path.is_file():
        raise InitError(f"Environment file does not exist: '{path}' (run `mellyn init` first).")

    values: dict[str, str] = {}
    for line_no, raw_line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            raise InitError(f"Malformed line {line_no} in '{path}': expected KEY=VALUE.")
        key, val = line.split("=", 1)
        clean_key = key.strip()
        if not clean_key:
            raise InitError(f"Empty variable name on line {line_no} in '{path}'.")
        clean_val = val.strip()
        if len(clean_val) >= 2 and clean_val[0] == clean_val[-1] and clean_val[0] in ("'", '"'):
            clean_val = clean_val[1:-1]
        values[clean_key] = clean_val
    return values


def _bare_filename(raw: str, variable: str) -> str:
    name = raw.strip()
    if not name or name in (".", "..") or any(sep in name for sep in ("/", "\\")):
        raise InitError(f"{variable} must be a plain file name inside the config folder, got '{raw}'.")
    return name


def resolve_stack_config(compose_file: Path, env: dict[str, str]) -> tuple[Path, Path, Path]:
    """
    Return (config_dir, policy_path, gateway_path) exactly as compose will resolve them for the containers.

    Compose resolves relative paths against the compose file's folder, and falls back to the checked-in examples.
    """
    compose_dir = compose_file.resolve().parent
    raw_dir = env.get(CONFIG_DIR_ENV, "").strip()
    config_dir = Path(raw_dir) if raw_dir else Path("..") / "config"
    if not config_dir.is_absolute():
        config_dir = compose_dir / config_dir
    policy_name = _bare_filename(env.get(POLICY_FILE_ENV, "") or DEFAULT_POLICY_FILE, POLICY_FILE_ENV)
    gateway_name = _bare_filename(env.get(GATEWAY_FILE_ENV, "") or DEFAULT_GATEWAY_FILE, GATEWAY_FILE_ENV)
    return config_dir.resolve(), (config_dir / policy_name).resolve(), (config_dir / gateway_name).resolve()


def run_up(
    *,
    compose_file: Path,
    squid_output: Path,
    policy_path: Path | None = None,
    env_file: Path | None = None,
    profiles: Sequence[str] = (),
    dry_run: bool = False,
) -> tuple[int, list[str]]:
    """
    Validate `.env` and the policy the containers will load, regenerate `squid.conf` from that same policy, and run
    `docker compose up -d --build` with `.env` passed to compose.

    `policy_path`, if given, must be the policy compose will mount: otherwise the Squid allowlist would come from
    one policy while the authorizer enforces another. With `dry_run`, nothing is written or started.
    """
    check_no_legacy_env()
    if compose_file.is_symlink() or not compose_file.is_file():
        raise InitError(f"Docker Compose file does not exist or is a symlink: '{compose_file}'.")
    _reject_symlink(squid_output)

    mellyn_env = {k: v for k, v in os.environ.items() if k.startswith("MELLYN_")}
    if env_file is not None:
        dotenv_values = parse_dotenv(env_file)
        check_no_legacy_env(dotenv_values)
        merged_env = {**dotenv_values, **mellyn_env}  # compose also lets the shell override the env file
        roles = {Role.AGENT, Role.APPROVER}
        if merged_env.get(DIGEST_ENV["viewer"], "").strip():
            roles.add(Role.VIEWER)
        CredentialConfig.from_env(merged_env, roles=frozenset(roles))
    else:
        merged_env = mellyn_env

    config_dir, stack_policy, stack_gateway = resolve_stack_config(compose_file, merged_env)
    if env_file is not None and env_file.resolve().parent == config_dir:
        raise InitError(
            f"'{env_file}' is inside the config folder '{config_dir}', which is mounted into the containers. "
            "Keep .env outside it."
        )
    for required in (stack_policy, stack_gateway):
        if required.is_symlink() or not required.is_file():
            raise InitError(f"Config file the containers would load does not exist or is a symlink: '{required}'.")
    if policy_path is not None and policy_path.resolve() != stack_policy:
        raise InitError(
            f"--policy '{policy_path}' is not the policy the containers will load ('{stack_policy}'); the Squid "
            f"allowlist would not match what the authorizer enforces. Set {CONFIG_DIR_ENV}/{POLICY_FILE_ENV} instead."
        )
    try:
        policy = load_policy_any(stack_policy)
        gateway_domains = load_gateway_egress_domains_any(stack_policy)
    except PolicyLoadError as exc:
        raise InitError(f"Policy rejected: {exc}") from exc
    squid_text = generate_squid_config(policy, gateway_domains=gateway_domains)

    argv: list[str] = ["docker", "compose"]
    if env_file is not None:
        argv.extend(["--env-file", str(env_file.resolve())])
    argv.extend(["-f", str(compose_file)])
    for raw_profile in profiles:
        prof = raw_profile.strip()
        if not prof or any(ch.isspace() for ch in prof):
            raise InitError(f"Invalid Compose profile '{raw_profile}'.")
        argv.extend(["--profile", prof])
    argv.extend(["up", "-d", "--build"])

    if dry_run:
        return 0, argv

    if shutil.which("docker") is None:
        raise InitError("Docker CLI ('docker') was not found on PATH.")

    squid_output.parent.mkdir(parents=True, exist_ok=True)
    squid_output.write_text(squid_text, encoding="utf-8", newline="\n")
    compose_env = dict(os.environ)
    if env_file is not None:
        # The containers load the same file compose interpolated, not whatever sits at the default ../.env.
        compose_env[ENV_FILE_ENV] = str(env_file.resolve())
    completed = subprocess.run(argv, check=False, env=compose_env)  # noqa: S603 - validated static docker compose argv
    return int(completed.returncode), argv
